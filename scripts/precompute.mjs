// Regenerates precomputed.js: token pieces for every sample × model, so the
// page can show results before any tokenizer is downloaded.
//
//   npm i @huggingface/tokenizers
//   node scripts/precompute.mjs
//
// Run it again whenever samples.js changes. Model ids must match app.js.
import { Tokenizer } from "@huggingface/tokenizers";
import fs from "node:fs";
import { SAMPLES } from "../samples.js";

const MODELS = {
  "gpt-4": "Xenova/gpt-4",
  "gpt-4o": "Xenova/gpt-4o",
  "llama3": "Xenova/llama3-tokenizer-new",
  "gemma2": "unsloth/gemma-2-2b",
  "qwen3": "Qwen/Qwen3-0.6B",
  "deepseek": "deepseek-ai/DeepSeek-V3",
  "mistral": "Xenova/mistral-tokenizer-v3",
  "bloom": "Xenova/bloom-560m",
};

const getJson = (repo, file) =>
  fetch(`https://huggingface.co/${repo}/resolve/main/${file}`).then((r) => {
    if (!r.ok) throw new Error(`${r.status} for ${repo}/${file}`);
    return r.json();
  });

// Word pair for the "how it works" strip, tokenized with GPT-4's tokenizer.
const WORD_PAIR = { en: "language", bn: "ভাষা" };

// Same grouping as piecesFromIds() in app.js. Each piece is [text, tokenIds].
function pieces(tok, ids) {
  const dec = (a) => tok.decode(a, { skip_special_tokens: true });
  const out = [];
  let buf = [], prev = [], prevText = "";
  for (const id of ids) {
    buf.push(id);
    const full = dec(prev.concat(buf));
    const text = full.startsWith(prevText) ? full.slice(prevText.length) : dec(buf);
    if (!text.includes("�")) { out.push([text, buf]); prev = buf; prevText = dec(prev); buf = []; }
  }
  if (buf.length) out.push([dec(buf), buf]);
  return out;
}

const PRE = {};
let WORDS = null;
for (const [id, repo] of Object.entries(MODELS)) {
  const tok = new Tokenizer(await getJson(repo, "tokenizer.json"), await getJson(repo, "tokenizer_config.json"));
  const cut = (text) => pieces(tok, tok.encode(text, { add_special_tokens: false }).ids);
  PRE[id] = SAMPLES.map((s) => ({ bn: cut(s.bn), en: cut(s.en) }));
  if (id === "gpt-4") WORDS = { model: id, en: cut(WORD_PAIR.en), bn: cut(WORD_PAIR.bn) };
  const count = (lang) => PRE[id].reduce((a, r) => a + r[lang].reduce((x, p) => x + p[1].length, 0), 0);
  console.log(id.padEnd(9), (count("bn") / count("en")).toFixed(2));
}

const out = `// Generated by scripts/precompute.mjs on ${new Date().toISOString().slice(0, 10)}.
// Token pieces for every sample in samples.js, per model. Each piece is
// [text, tokenIds]. Lets the page show results before any tokenizer is
// downloaded. Regenerate when samples.js changes.
export const PRECOMPUTED = ${JSON.stringify(PRE)};
export const WORDS = ${JSON.stringify(WORDS)};
`;
fs.writeFileSync(new URL("../precomputed.js", import.meta.url), out);
console.log("wrote precomputed.js");
